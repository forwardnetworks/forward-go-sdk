// Command gen writes vendoros_gen.go from Forward's VendorProtos.proto, so the OS-to-number table is never
// copied by hand:
//
//	go run ./perfpayload/gen -proto $FORWARD_SOURCE/client-structs/src/main/proto/com/forwardnetworks/client/device/VendorProtos.proto -commit $(git -C $FORWARD_SOURCE rev-parse HEAD) > perfpayload/vendoros_gen.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	proto := flag.String("proto", "", "path to VendorProtos.proto")
	commit := flag.String("commit", "unknown", "Forward source commit the proto was read at")
	flag.Parse()
	f, err := os.Open(*proto)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	re := regexp.MustCompile(`^\s*VENDOR_OS_([A-Z0-9_]+)\s*=\s*(\d+)\s*;`)
	inEnum := false
	vals := map[string]int{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case regexp.MustCompile(`^\s*enum\s+VendorOsPB\s*\{`).MatchString(line):
			inEnum = true
		case inEnum && regexp.MustCompile(`^\s*\}`).MatchString(line):
			inEnum = false
		case inEnum:
			if m := re.FindStringSubmatch(line); m != nil {
				n, _ := strconv.Atoi(m[2])
				vals[m[1]] = n
			} else if strings.Contains(line, "VENDOR_OS_") && !strings.HasPrefix(strings.TrimSpace(line), "//") {
				fmt.Fprintf(os.Stderr, "unparsed enum line: %s\n", line)
				os.Exit(1)
			}
		}
	}
	var out bytes.Buffer
	if len(vals) == 0 {
		fmt.Fprintln(os.Stderr, "no VENDOR_OS_ values found: is this VendorProtos.proto?")
		os.Exit(1)
	}
	names := make([]string, 0, len(vals))
	for n := range vals {
		names = append(names, n)
	}
	sort.Strings(names)
	fmt.Fprintf(&out, "// Code generated by perfpayload/gen from Forward's VendorProtos.proto (VendorOsPB); DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: Forward commit %s\n\npackage perfpayload\n\n", *commit)
	fmt.Fprintf(&out, "// VendorOS maps Forward's platform OS name (as NQE returns it) to the VendorOsPB number.\nvar VendorOS = map[string]int32{\n")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%q: %d,\n", n, vals[n])
	}
	fmt.Fprintf(&out, "}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(src)
}
